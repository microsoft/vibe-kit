# Minimum percent identity to flag a sequence (T34 — variant detection)
SIMILARITY_THRESHOLD = 0.70  # 70% identity


# ---------------------------------------------------------------------------
# Screening functions
# ---------------------------------------------------------------------------

def _percent_identity(seq1: str, seq2: str) -> float:
    """
    Simple percent identity between two sequences.
    Uses the shorter sequence as the reference length.
    Not a proper alignment — just a sliding window match.
    For production, use BLAST or MMseqs2.
    """
    seq1 = seq1.upper().strip()
    seq2 = seq2.upper().strip()

    if not seq1 or not seq2:
        return 0.0

    # If lengths are very different, skip expensive comparison
    shorter, longer = (seq1, seq2) if len(seq1) <= len(seq2) else (seq2, seq1)
    if len(shorter) / len(longer) < SIMILARITY_THRESHOLD:
        return 0.0

    # Simple ungapped alignment: count matching positions
    matches = sum(1 for a, b in zip(shorter, longer) if a == b)
    return matches / len(shorter)


def screen_sequence(sequence: str) -> Optional[str]:
    """
    Screen a protein sequence against Select Agent toxin database.

    Returns:
        None if the sequence is allowed.
        A string reason code if blocked (do NOT expose to user).
    """
    sequence = sequence.upper().strip()

    if not sequence:
        return None

    for name, toxin_seq in TOXIN_SEQUENCES.items():
        # Exact match
        if sequence == toxin_seq.upper():
            return f"exact_match:{name}"

        # Subsequence match (user submits a fragment of a toxin)
        if sequence in toxin_seq.upper() or toxin_seq.upper() in sequence:
            return f"subsequence:{name}"

        # Percent identity match (variant detection, T34)
        identity = _percent_identity(sequence, toxin_seq)
        if identity >= SIMILARITY_THRESHOLD:
            return f"similarity:{name}:{identity:.2f}"

    return None
